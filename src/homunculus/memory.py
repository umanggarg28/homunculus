"""The agent's memory: a wiki of plain markdown files in a private git repository.

The layout follows Karpathy's LLM Wiki pattern: raw sources that are never edited, a
wiki the agent writes and maintains, a schema that says how the wiki is organised, a
generated index and an append-only log. The profile and the goals sit beside them.

    raw/        sources, never edited by the agent
    wiki/       pages the agent writes
      index.md    generated by code from each page's title and summary
      log.md      appended by code on every change
    profile.md  short, always in the prompt
    goals.md    the operator's goals; changed only with approval
    SCHEMA.md   how the wiki is organised; changed only with approval

The file tools reach this folder through paths that start with `memory/`. What the
agent may change is decided by the gate; whether a change is well formed is checked
here, before anything is written, so a bad write leaves no trace.
"""

import hashlib
import re
import subprocess
import threading
from dataclasses import dataclass
from datetime import datetime
from importlib.resources import files
from pathlib import Path, PurePosixPath

from homunculus.tools import ToolError

# Always-loaded context stays small: these caps keep profile, goals and index together
# near 2,500 tokens. Counted in characters, so they do not depend on any one model.
CAPS = {"profile.md": 2000, "goals.md": 2000, "wiki/index.md": 6000}

# Commits name who made a change, which is how a hand edit is recognised later.
AGENT = ("Homunculus", "agent@homunculus.local")
OPERATOR = ("Operator", "operator@homunculus.local")

INDEX = "wiki/index.md"
LOG = "wiki/log.md"
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
FOOTNOTE_USE = re.compile(r"\[\^([^\]]+)\](?!:)")
FOOTNOTE_DEFINITION = re.compile(r"^\[\^([^\]]+)\]:\s*(\S+)", re.M)
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
LOG_ENTRY = re.compile(r"^## \[([^\]]+)\] (.+?) \| (.+)$", re.M)
# Sections whose lines are navigation, not facts, so they need no source.
UNSOURCED_SECTIONS = {"See also"}


class Stale(Exception):
    """A save made from a version of the file that is no longer the current one."""


@dataclass(frozen=True)
class Change:
    """A change the file tools are about to make, for the checks to judge."""

    tool: str
    path: str  # relative to the memory folder
    before: str | None  # the file as it is now, or None if it does not exist
    after: str | None  # the file as it will be, or None if it is going away


class Memory:
    def __init__(self, root: Path) -> None:
        self.root = root
        # Held for the whole of each change, by the agent's file tools and by the
        # console's saves. Tools run in worker threads, so without it a save could land
        # between the agent writing a file and committing it, and be credited wrongly.
        self.lock = threading.RLock()

    @classmethod
    def open(cls, root: Path) -> "Memory":
        """The memory at `root`, created empty on first use. The wiki starts empty so
        nothing from an earlier version leaks in."""
        if not (root / ".git").is_dir():
            root.mkdir(parents=True, exist_ok=True)
            (root / "raw").mkdir(exist_ok=True)
            (root / "wiki").mkdir(exist_ok=True)
            starting = {
                "profile.md": "# Profile\n\n## How I like to work\n",
                "goals.md": "# Goals\n",
                "SCHEMA.md": files("homunculus").joinpath("schema.md").read_text(encoding="utf-8"),
                LOG: "# Log\n",
            }
            for name, text in starting.items():
                if not (root / name).exists():
                    (root / name).write_text(text, encoding="utf-8")
            memory = cls(root.resolve())
            memory._git("init", "--quiet")
            memory._write_index()
            memory._commit(AGENT, "Start the memory")
        return cls(root.resolve())

    # The prompt

    def context(self) -> str:
        """The always-loaded part of memory, each with how much of its budget it uses,
        so the model can see when one is nearly full."""
        parts = []
        for title, name in [
            ("Profile", "profile.md"),
            ("Goals", "goals.md"),
            ("Wiki index", INDEX),
        ]:
            text = self._read(name) or ""
            cap = CAPS[name]
            shown = text if len(text) <= cap else text[:cap] + "\n(cut at the cap)"
            if name == INDEX:
                # The file links pages relative to wiki/, as any markdown viewer expects; the
                # model reads them by the path its file tools take.
                shown = re.sub(r"\]\(([^)]+)\)", r"](memory/wiki/\1)", shown)
            parts.append(f"### {title} ({len(text):,} of {cap:,} characters)\n\n{shown.strip()}")
        return "## In memory now\n\n" + "\n\n".join(parts)

    # Before and after a change

    def take_hand_edits(self) -> None:
        """Record any change on disk that the agent did not make as the operator's own,
        so it is never mistaken for the agent's work and never rewritten whole."""
        changed = self._changed_paths()
        if not changed:
            return
        for path in changed:
            self._log("hand edit", path)
        self._write_index()
        self._commit(OPERATOR, "Hand edit: " + ", ".join(changed))

    def check(self, change: Change) -> None:
        """Refuse a change that would leave the memory badly formed, saying why in words
        the model can act on. Only the lines the change adds are checked for sources, so
        the operator's own notes never block the agent."""
        path = change.path
        if change.before is not None and change.after is not None and change.tool == "write":
            if self.hand_edited(path):
                raise ToolError(
                    f"{path} cannot be rewritten whole: you edited it by hand. "
                    "Use edit to add to it or change one part."
                )
        if change.after is None:
            return
        if path in CAPS and len(change.after) > CAPS[path]:
            raise ToolError(
                f"{path} would be {len(change.after):,} characters, over its cap of "
                f"{CAPS[path]:,} characters. Make it shorter."
            )
        if path == "profile.md":
            if re.search(r"^## Inferred\s*$", change.after, re.M):
                raise ToolError(
                    "The profile holds only stated facts. Keep inferred facts on wiki pages, "
                    "under ## Inferred, until the operator confirms them."
                )
            self._check_sources(path, change)
        elif path.startswith("wiki/"):
            fields = _frontmatter(change.after)
            if not fields.get("title") or not fields.get("summary"):
                raise ToolError(
                    f"{path} needs a title and a summary in its frontmatter, between --- lines "
                    "at the top. See memory/SCHEMA.md."
                )
            self._check_sources(path, change)
            self._check_links(path, change)

    def record(self, tool: str, path: str, to: str | None = None) -> str:
        """After a change: regenerate the index, log it, commit it. Returns a note for
        the model, such as a page nothing links to yet."""
        self._log(tool, path if to is None else f"{path} -> {to}")
        self._write_index()
        self._commit(AGENT, f"{tool} {path}" if to is None else f"{tool} {path} to {to}")
        landed = to or path
        if (
            landed.startswith("wiki/")
            and landed not in (INDEX, LOG)
            and (self.root / landed).exists()
        ):
            if not self._linked_from_elsewhere(landed):
                return f" No other page links to {landed} yet."
        return ""

    def hand_edited(self, path: str) -> bool:
        authors = self._git("log", "--format=%an", "--", path).split()
        return OPERATOR[0] in authors

    # What the console reads and saves

    def pages(self) -> list[dict[str, str | int]]:
        """Each wiki page with its title, summary and how many guesses wait on it."""
        listed: list[dict[str, str | int]] = []
        for page in self._pages():
            text = self._read(page) or ""
            fields = _frontmatter(text)
            listed.append(
                {
                    "path": page,
                    "title": fields.get("title") or page,
                    "summary": fields.get("summary", ""),
                    "guesses": _guesses(text),
                }
            )
        return listed

    def page(self, path: str) -> dict[str, str]:
        """A page the operator may read and edit: a wiki page, or the profile."""
        name = self._editable(path)
        text = self._read(name) or ""
        return {"path": name, "text": text, "version": _version(text)}

    def save(self, path: str, text: str, version: str) -> dict[str, str]:
        """Save the operator's edit, made from `version`, as their hand edit. The agent's
        checks do not apply: the operator is the source of their own corrections. Only
        the caps do, because they keep the prompt small whoever writes."""
        with self.lock:
            return self._save(path, text, version)

    def _save(self, path: str, text: str, version: str) -> dict[str, str]:
        name = self._editable(path)
        # Anything already changed on disk is recorded as it is, apart from this save.
        self.take_hand_edits()
        if _version(self._read(name) or "") != version:
            raise Stale(f"{name} has changed since you opened it.")
        if name in CAPS and len(text) > CAPS[name]:
            raise ValueError(
                f"{name} would be {len(text):,} characters, over its cap of {CAPS[name]:,}."
            )
        (self.root / name).write_text(text, encoding="utf-8")
        self.take_hand_edits()
        return self.page(name)

    def sources(self) -> list[dict[str, str | None]]:
        """Every file under raw/, with when it first entered the memory."""
        with self.lock:
            self.take_hand_edits()
        added: dict[str, str] = {}
        when = ""
        # Newest first, so the last date seen for a file is when it was first added.
        for line in self._git(
            "log", "--diff-filter=A", "--format=@%aI", "--name-only", "--", "raw"
        ).splitlines():
            if line.startswith("@"):
                when = line[1:]
            elif line:
                added[line] = when
        raw = self.root / "raw"
        found = sorted(p.relative_to(self.root).as_posix() for p in raw.rglob("*") if p.is_file())
        return [{"path": path, "added": added.get(path)} for path in found]

    def source(self, path: str) -> dict[str, str]:
        """A raw source as it is. Read only: nothing here changes one."""
        name = _normal(PurePosixPath(path))
        file = self.root / name if name else None
        if (
            name is None
            or not name.startswith("raw/")
            or file is None
            or file.is_symlink()
            or not file.is_file()
        ):
            raise LookupError(path)
        return {"path": name, "text": file.read_text(encoding="utf-8", errors="replace")}

    def log(self) -> list[dict[str, str]]:
        """The log's entries, newest first."""
        entries = LOG_ENTRY.findall(self._read(LOG) or "")
        return [{"time": t, "action": a, "path": p} for t, a, p in reversed(entries)]

    def _editable(self, path: str) -> str:
        name = _normal(PurePosixPath(path))
        if name == "profile.md" or (name and name in self._pages()):
            file = self.root / name
            if not file.is_symlink() and file.is_file():
                return name
        raise LookupError(path)

    # Checks

    def _check_sources(self, path: str, change: Change) -> None:
        """Every new line that states something names a source, and every source is a
        raw file that exists."""
        assert change.after is not None
        definitions = dict(FOOTNOTE_DEFINITION.findall(change.after))
        old = set((change.before or "").splitlines())
        section = ""
        body = FRONTMATTER.sub("", change.after, count=1)
        for line in body.splitlines():
            stripped = line.strip()
            if stripped.startswith("#"):
                section = stripped.lstrip("#").strip()
                continue
            if not stripped or FOOTNOTE_DEFINITION.match(stripped) or line in old:
                continue
            if section in UNSOURCED_SECTIONS:
                continue
            uses = FOOTNOTE_USE.findall(stripped)
            if not uses:
                raise ToolError(
                    f"This line in {path} has no source: {stripped!r}. End each fact with a "
                    "footnote such as [^1], and define it as [^1]: raw/<the source file>."
                )
            for name in uses:
                if name not in definitions:
                    raise ToolError(f"{path} uses the footnote [^{name}] but never defines it.")
        for name, target in definitions.items():
            source = PurePosixPath(target)
            if source.parts[:1] != ("raw",) or ".." in source.parts:
                raise ToolError(f"The source [^{name}] in {path} must be a file under raw/.")
            if not (self.root / source).is_file():
                raise ToolError(f"The source [^{name}] in {path}: {target} does not exist.")

    def _check_links(self, path: str, change: Change) -> None:
        assert change.after is not None
        folder = PurePosixPath(path).parent
        for target in LINK.findall(change.after):
            if "://" in target or target.startswith("#"):
                continue
            resolved = _normal(folder / target.split("#", 1)[0])
            if resolved is None or not (self.root / resolved).is_file():
                raise ToolError(f"{path} links to {target}, which does not exist.")

    def _linked_from_elsewhere(self, path: str) -> bool:
        for page in self._pages():
            if page == path:
                continue
            folder = PurePosixPath(page).parent
            for target in LINK.findall(self._read(page) or ""):
                if _normal(folder / target.split("#", 1)[0]) == path:
                    return True
        return False

    # The index and the log

    def _pages(self) -> list[str]:
        wiki = self.root / "wiki"
        found = (p.relative_to(self.root).as_posix() for p in wiki.rglob("*.md"))
        return sorted(p for p in found if p not in (INDEX, LOG))

    def _write_index(self) -> None:
        """The index is built from each page's own title and summary, so it never drifts
        from the pages and the model never has to keep it up to date."""
        lines = ["# Index", ""]
        for page in self._pages():
            fields = _frontmatter(self._read(page) or "")
            link = PurePosixPath(page).relative_to("wiki").as_posix()
            title = fields.get("title") or link
            lines.append(f"- [{title}]({link}): {fields.get('summary', '')}".rstrip(": "))
        (self.root / INDEX).write_text("\n".join(lines) + "\n", encoding="utf-8")

    def _log(self, action: str, path: str) -> None:
        stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
        with (self.root / LOG).open("a", encoding="utf-8") as log:
            log.write(f"\n## [{stamp}] {action} | {path}\n")

    # Files and git

    def _read(self, name: str) -> str | None:
        path = self.root / name
        return path.read_text(encoding="utf-8") if path.is_file() else None

    def _changed_paths(self) -> list[str]:
        out = self._git("status", "--porcelain", "--untracked-files=all")
        return sorted(line[3:].strip('"') for line in out.splitlines() if line[3:])

    def _commit(self, who: tuple[str, str], message: str) -> None:
        self._git("add", "--all")
        name, email = who
        self._git(
            "-c", f"user.name={name}", "-c", f"user.email={email}",
            "commit", "--quiet", "--allow-empty", "--no-verify", "-m", message,
        )  # fmt: skip

    def _git(self, *arguments: str) -> str:
        # The repository is only ever local: no remote is set, and nothing is pushed.
        return subprocess.run(
            ["git", *arguments], cwd=self.root, capture_output=True, text=True, check=True
        ).stdout


def _frontmatter(text: str) -> dict[str, str]:
    match = FRONTMATTER.match(text)
    return dict(_field(line) for line in match.group(1).splitlines()) if match else {}


def _guesses(text: str) -> int:
    """Lines under ## Inferred that state something, struck lines aside."""
    count, inside = 0, False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            inside = re.fullmatch(r"#+\s*Inferred", stripped) is not None
        elif inside and stripped and not FOOTNOTE_DEFINITION.match(stripped):
            count += not stripped.startswith("~~")
    return count


def _version(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _field(line: str) -> tuple[str, str]:
    key, _, value = line.partition(":")
    return key.strip(), value.strip()


def _normal(path: PurePosixPath) -> str | None:
    """A path inside the memory folder with '..' worked out, or None if it leaves it."""
    parts: list[str] = []
    for part in path.parts:
        if part == "..":
            if not parts:
                return None
            parts.pop()
        elif part != ".":
            parts.append(part)
    return "/".join(parts)
